// Licence gate for the production dependency tree (ADR-0011).
//   node scripts/check-licences.mjs                 check, exit 1 on violations
//   node scripts/check-licences.mjs --write-notices also regenerate docs/third-party.md
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** @typedef {{allowed:string[],allowedWithCare:string[],needsReview:string[],forbidden:string[],exceptions:{name:string,reason:string}[]}} Policy */

/** @returns {Policy} */
export function loadPolicy() {
  return JSON.parse(readFileSync(resolve(root, 'scripts/licence-policy.json'), 'utf8'));
}

/**
 * Classify one SPDX identifier.
 * @param {string} id @param {Policy} policy
 * @returns {'allowed'|'care'|'review'|'forbidden'|'unknown'}
 */
export function classifyId(id, policy) {
  const value = id.trim();
  // Exact matches first: "LGPL-2.1" contains "GPL" but needs review, not an outright ban.
  if (policy.needsReview.includes(value)) return 'review';
  if (policy.allowedWithCare.includes(value)) return 'care';
  if (policy.allowed.includes(value)) return 'allowed';
  if (policy.forbidden.some((f) => value.toUpperCase().includes(f.toUpperCase())))
    return 'forbidden';
  return 'unknown';
}

const RANK = { allowed: 0, care: 1, review: 2, unknown: 3, forbidden: 4 };

/**
 * Evaluate an SPDX-style expression: "(MIT OR Apache-2.0)", "MIT AND Zlib", or a single id.
 * OR picks the best option, AND takes the worst.
 * @param {string} expression @param {Policy} policy
 */
export function classifyExpression(expression, policy) {
  const tokens = expression
    .replace(/\(/g, ' ( ')
    .replace(/\)/g, ' ) ')
    .split(/\s+/)
    .filter(Boolean);
  let pos = 0;
  const parseOr = () => {
    let best = parseAnd();
    while (tokens[pos]?.toUpperCase() === 'OR') {
      pos += 1;
      const next = parseAnd();
      if (RANK[next] < RANK[best]) best = next;
    }
    return best;
  };
  const parseAnd = () => {
    let worst = parseAtom();
    while (tokens[pos]?.toUpperCase() === 'AND') {
      pos += 1;
      const next = parseAtom();
      if (RANK[next] > RANK[worst]) worst = next;
    }
    return worst;
  };
  const parseAtom = () => {
    const token = tokens[pos++];
    if (token === '(') {
      const inner = parseOr();
      if (tokens[pos] === ')') pos += 1;
      return inner;
    }
    return classifyId(token ?? '', policy);
  };
  return parseOr();
}

/**
 * Evaluate the output of `pnpm licenses list --json` ({ [licence]: [{name, versions}] }).
 * @param {Record<string, {name:string, versions:string[]}[]>} licenseMap @param {Policy} policy
 */
export function evaluateLicences(licenseMap, policy) {
  const excepted = new Set(policy.exceptions.map((e) => e.name));
  /** @type {{name:string,version:string,licence:string,status:string}[]} */
  const entries = [];
  for (const [licence, packages] of Object.entries(licenseMap)) {
    const status = classifyExpression(licence, policy);
    for (const pkg of packages) {
      for (const version of pkg.versions) {
        entries.push({ name: pkg.name, version, licence, status });
      }
    }
  }
  const violations = entries.filter(
    (e) =>
      (e.status === 'forbidden' || e.status === 'unknown' || e.status === 'review') &&
      !excepted.has(e.name),
  );
  const care = entries.filter((e) => e.status === 'care');
  return { entries, violations, care };
}

function readLicenseMap() {
  const args = ['licenses', 'list', '--prod', '--json'];
  const options = { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 };
  // When started through `pnpm run`, pnpm exposes its own entry script: run it with node (no shell needed).
  const pnpmScript = process.env.npm_execpath;
  const out =
    pnpmScript && /pnpm\.c?js$/.test(pnpmScript)
      ? execFileSync(process.execPath, [pnpmScript, ...args], options)
      : execFileSync('pnpm', args, { ...options, shell: process.platform === 'win32' });
  return JSON.parse(out);
}

function renderNotices(entries) {
  const rows = [...entries]
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
    .map((e) => `| ${e.name} | ${e.version} | ${e.licence} |`);
  return [
    '# Third-party notices',
    '',
    'Generated by `pnpm check:notices` from the production dependency tree. Do not edit by hand.',
    'WASM binaries, fonts and AI model weights are listed separately below when they exist.',
    '',
    '## npm packages (production)',
    '',
    '| Package | Version | Licence |',
    '|---|---|---|',
    ...rows,
    '',
    '## Fonts, WASM binaries and models',
    '',
    'None yet.',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const policy = loadPolicy();
  const { entries, violations, care } = evaluateLicences(readLicenseMap(), policy);
  console.log(`Checked ${entries.length} production packages.`);
  for (const c of care)
    console.log(`  note (allowed with care): ${c.name}@${c.version} ${c.licence}`);
  if (process.argv.includes('--write-notices')) {
    writeFileSync(resolve(root, 'docs/third-party.md'), renderNotices(entries));
    console.log('Wrote docs/third-party.md');
  }
  if (violations.length > 0) {
    console.error('\nLicence policy violations:');
    for (const v of violations)
      console.error(`  ${v.name}@${v.version}: ${v.licence} (${v.status})`);
    process.exit(1);
  }
  console.log('Licence policy: OK');
}
